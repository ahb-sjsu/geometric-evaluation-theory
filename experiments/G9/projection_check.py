"""How often does reading a 5-D evaluator on 2 coordinates invent a hull violation?

Exactly G9's configuration. Four actions, a five-dimensional consequence space,
a ranking generated by a genuine convex quadratic evaluator in that space, and
the hull law then read on two of the five coordinates as the gate reads it.

In its own space such a ranking cannot violate the law. Whatever violation rate
appears on the plane is manufactured by the projection.
"""
import importlib.util
import sys

import numpy as np

G2 = "/home/claude/g2_hull_law.py"
spec = importlib.util.spec_from_file_location("g2_hull_law", G2)
g2 = importlib.util.module_from_spec(spec)
sys.modules["g2_hull_law"] = g2
spec.loader.exec_module(g2)

rng = np.random.default_rng(20260919)
DIM, N_ACT, TRIALS = 5, 4, 4000

full_t = full_v = proj_t = proj_v = 0
for i in range(TRIALS):
    Y = rng.normal(size=(N_ACT, DIM))
    A = rng.normal(size=(DIM, DIM))
    G = A @ A.T + 0.1 * np.eye(DIM)
    t = rng.normal(size=DIM)
    d = Y - t
    T = -np.einsum("ij,jk,ik->i", d, G, d)

    r = g2.evaluate_respondent(Y, T)
    full_t += int(r.testable)
    full_v += int(r.violated and r.testable)

    j, k = rng.choice(DIM, size=2, replace=False)
    rp = g2.evaluate_respondent(Y[:, [j, k]], T)
    proj_t += int(rp.testable)
    proj_v += int(rp.violated and rp.testable)

    if (i + 1) % 1000 == 0:
        print("trial %d  full %d/%d  proj %d/%d" % (i + 1, full_v, full_t, proj_v, proj_t),
              flush=True)

print(flush=True)
print("In the evaluator's own 5-D space: %d testable, %d violating, rate %s"
      % (full_t, full_v, ("%.4f" % (full_v / full_t)) if full_t else "n/a"), flush=True)
print("Read on 2 of the 5 coordinates: %d testable, %d violating, rate %s"
      % (proj_t, proj_v, ("%.4f" % (proj_v / proj_t)) if proj_t else "n/a"), flush=True)
print(flush=True)
print("Every violation in the second line is manufactured by the projection,", flush=True)
print("because the ranking came from a genuine convex evaluator.", flush=True)
